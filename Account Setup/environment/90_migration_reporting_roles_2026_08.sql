GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_NET_ENGINEERING)        TO ROLE IDENTIFIER($R_RPT_NET_ENGINEERING);

-- No schema grants: a domain role gets access when its GOLD_{domain}
-- mart is built. See the pattern at the end of 04.


-- ============================================================
-- 2. ADD  -  {ENV}_POWERBI and rewire the service user
--    {ENV}_REPORTER keeps existing, but becomes the HUMAN role for
--    the shared GOLD schema. Its grants on GOLD are already correct.
-- ============================================================
USE ROLE IDENTIFIER($ENV_USERADMIN);
CREATE ROLE IF NOT EXISTS IDENTIFIER($R_POWERBI);
GRANT ROLE IDENTIFIER($R_POWERBI) TO ROLE IDENTIFIER($ENV_SYSADMIN);

USE ROLE IDENTIFIER($ENV_SYSADMIN);
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($W_POWERBI)
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_POWERBI) TO ROLE IDENTIFIER($R_POWERBI);

-- Read on the shared GOLD schema.
SET GOLD_RO = $DB_NAME || '.GOLD_RO_AR';
GRANT DATABASE ROLE IDENTIFIER($GOLD_RO) TO ROLE IDENTIFIER($R_POWERBI);

-- Rewire SVC_{ENV}_POWERBI. CREATE USER IF NOT EXISTS in 05 does not
-- update an existing user, so these have to be explicit.
USE ROLE IDENTIFIER($ENV_USERADMIN);
GRANT ROLE IDENTIFIER($R_POWERBI) TO USER IDENTIFIER($SVC_PBI_USER);
ALTER USER IDENTIFIER($SVC_PBI_USER) SET
    DEFAULT_ROLE      = $R_POWERBI,
    DEFAULT_WAREHOUSE = $W_POWERBI;

-- Remove the old role from the service user LAST, so the user is never
-- left without a working role.
REVOKE ROLE IDENTIFIER($R_REPORTER) FROM USER IDENTIFIER($SVC_PBI_USER);


-- ============================================================
-- 3. DROP  -  the three placeholder domain reporter roles
--    Destructive. Section 0 must have shown no user grants.
-- ============================================================
USE ROLE IDENTIFIER($ENV_SYSADMIN);
DROP WAREHOUSE IF EXISTS IDENTIFIER($W_OLD_BILLING);
DROP WAREHOUSE IF EXISTS IDENTIFIER($W_OLD_FINANCE);
DROP WAREHOUSE IF EXISTS IDENTIFIER($W_OLD_MARKETING);

USE ROLE IDENTIFIER($ENV_USERADMIN);
DROP ROLE IF EXISTS IDENTIFIER($R_OLD_BILLING);
DROP ROLE IF EXISTS IDENTIFIER($R_OLD_FINANCE);
DROP ROLE IF EXISTS IDENTIFIER($R_OLD_MARKETING);


-- ============================================================
-- 4. DROP  -  the three placeholder GOLD marts
--    DROP_SCHEMA removes the schema AND its RO/RW/FULL database roles.
--    It refuses if the schema does not exist, and returns a message
--    rather than raising - read the result of each call.
--    Destructive. Section 0 must have shown these schemas empty.
-- ============================================================
USE ROLE IDENTIFIER($ENV_SYSADMIN);
USE DATABASE PLATFORM_DB;
USE SCHEMA RBAC;

CALL PLATFORM_DB.RBAC.DROP_SCHEMA($DB_NAME, 'GOLD_BILLING');
CALL PLATFORM_DB.RBAC.DROP_SCHEMA($DB_NAME, 'GOLD_FINANCE');
CALL PLATFORM_DB.RBAC.DROP_SCHEMA($DB_NAME, 'GOLD_MARKETING');


-- ============================================================
-- 5. VALIDATION
-- ============================================================
USE ROLE IDENTIFIER($ENV_SYSADMIN);

-- Expect 20 roles: 4 human + 13 domain reporters + 3 service.
-- The three _BILLING / _FINANCE / _MARKETING roles must be gone.
SHOW ROLES LIKE $ENV_ABBR || '%';

-- Expect 20 warehouses, same rule.
SHOW WAREHOUSES LIKE $ENV_ABBR || '%';

-- Expect 6 schemas: ADM, RAW, BRONZE, BRONZE_HIST, SILVER, GOLD.
SHOW SCHEMAS IN DATABASE IDENTIFIER($DB_NAME);

-- Expect DEFAULT_ROLE {ENV}_POWERBI and DEFAULT_WAREHOUSE
-- {ENV}_POWERBI_WH.
DESC USER IDENTIFIER($SVC_PBI_USER);

-- Expect {ENV}_POWERBI only - {ENV}_REPORTER must no longer be here.
SHOW GRANTS TO USER IDENTIFIER($SVC_PBI_USER);

-- Orphan check: no database role should remain for a dropped schema.
SHOW DATABASE ROLES IN DATABASE IDENTIFIER($DB_NAME);
