SET W_RPT_SMC_MARKETING_COMMS    = $ENV_ABBR || 'REPORTER_SMC_MARKETING_COMMS_WH';
SET W_RPT_SMC_SALES              = $ENV_ABBR || 'REPORTER_SMC_SALES_WH';
