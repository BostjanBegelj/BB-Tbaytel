    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($W_RPT_HR_OCCUPATIONAL_HEALTH)
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($W_RPT_NET_IT_SECURITY)
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($W_RPT_NET_NETWORK_OPS)
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($W_RPT_NET_ENGINEERING)
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_SMC_MARKETING_COMMS)    TO ROLE IDENTIFIER($R_RPT_SMC_MARKETING_COMMS);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_SMC_SALES)              TO ROLE IDENTIFIER($R_RPT_SMC_SALES);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_FIN_ACCOUNTING)         TO ROLE IDENTIFIER($R_RPT_FIN_ACCOUNTING);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_FIN_FPNA)               TO ROLE IDENTIFIER($R_RPT_FIN_FPNA);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_FIN_PROCUREMENT)        TO ROLE IDENTIFIER($R_RPT_FIN_PROCUREMENT);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_OPE_CUSTOMER_CARE)      TO ROLE IDENTIFIER($R_RPT_OPE_CUSTOMER_CARE);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_OPE_FIELD_OPERATIONS)   TO ROLE IDENTIFIER($R_RPT_OPE_FIELD_OPERATIONS);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_HR_PAYROLL)             TO ROLE IDENTIFIER($R_RPT_HR_PAYROLL);
GRANT USAGE ON WAREHOUSE IDENTIFIER($W_RPT_HR_HEALTH_SAFETY)       TO ROLE IDENTIFIER($R_RPT_HR_HEALTH_SAFETY);
