SET W_RPT_FIN_FPNA               = $ENV_ABBR || 'REPORTER_FIN_FPNA_WH';
SET W_RPT_FIN_PROCUREMENT        = $ENV_ABBR || 'REPORTER_FIN_PROCUREMENT_WH';
SET W_RPT_OPE_CUSTOMER_CARE      = $ENV_ABBR || 'REPORTER_OPE_CUSTOMER_CARE_WH';
SET W_RPT_OPE_FIELD_OPERATIONS   = $ENV_ABBR || 'REPORTER_OPE_FIELD_OPERATIONS_WH';
SET W_RPT_HR_PAYROLL             = $ENV_ABBR || 'REPORTER_HR_PAYROLL_PEOPLE_TALENT_WH';
SET W_RPT_HR_HEALTH_SAFETY       = $ENV_ABBR || 'REPORTER_HR_HEALTH_SAFETY_WH';
SET W_RPT_HR_OCCUPATIONAL_HEALTH = $ENV_ABBR || 'REPORTER_HR_OCCUPATIONAL_HEALTH_WH';
SET W_RPT_NET_IT_SECURITY        = $ENV_ABBR || 'REPORTER_NET_IT_SECURITY_WH';
SET W_RPT_NET_NETWORK_OPS        = $ENV_ABBR || 'REPORTER_NET_NETWORK_OPERATIONS_WH';
