-- ============================================================
-- ENVIRONMENT FUNCTIONAL ROLES + VIRTUAL WAREHOUSES
-- RUN PER ENVIRONMENT.  Set ENV_ABBR, then run the whole file.
--
-- These roles hold the PRIVILEGES and stay owned by {ENV}_USERADMIN.
-- Entra groups are synced in by SCIM as separate roles that hold no
-- privileges; each is granted the matching role here, once, in
-- account/17. Entra manages membership, Snowflake manages access.
--
-- HUMAN roles (an Entra group is granted each one):
--   TRANSFORMER         data engineering / transformation
