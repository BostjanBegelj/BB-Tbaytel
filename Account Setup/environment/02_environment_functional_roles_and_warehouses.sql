--   REPORTER            reporting on the shared GOLD schema
--   IT_GOVERNANCE       governance / monitoring / admin reporting
--   REPORTER_{domain}   reporting on one GOLD_{domain} mart (13)
--
-- SERVICE roles (no Entra group - used by SVC_ users in 05):
--   DATA_LOADER         Azure Data Factory ingestion
--   DEPLOYER            CI/CD deployment (schemachange/dbt)
--   POWERBI             Power BI service account, reads GOLD + all marts
--
-- Each role gets its own warehouse for per-workload cost attribution.
-- Warehouses are created suspended and cost nothing until used.
-- ============================================================
